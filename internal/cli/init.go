package cli

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/akhanatoon/quench/internal/config"
	"github.com/spf13/cobra"
)

func newInitCmd() *cobra.Command {
	var force bool

	cmd := &cobra.Command{
		Use:   "init",
		Short: "Detect project stack and generate a starter quench.yaml",
		RunE: func(cmd *cobra.Command, args []string) error {
			projectDir, err := resolveProjectDir()
			if err != nil {
				return err
			}

			outPath := filepath.Join(projectDir, config.ConfigFileName)
			if !force {
				if _, statErr := os.Stat(outPath); statErr == nil {
					return fmt.Errorf("%s already exists (use --force to overwrite)", outPath)
				}
			}

			cfg, err := config.DetectConfig(projectDir)
			if err != nil {
				// Generate a clean generic starter template if stack is unknown
				syncDeps := false
				cfg = &config.Config{
					Version:        1,
					Mode:           config.ModeLocal,
					Stack:          config.StackGeneric,
					DefaultTimeout: "120s",
					Sandbox: config.SandboxConfig{
						Image:       "alpine:3.20",
						IdleTimeout: "30m",
						Network:     "bridge",
						SyncDeps:    &syncDeps,
					},
					Checks: []config.CheckConfig{
						{
							Name:    "test",
							Command: "echo 'Configure your test command in quench.yaml'",
							Scope:   config.ScopeProject,
							Timeout: "120s",
						},
					},
				}
			}

			if cfg.DefaultTimeout == "" {
				cfg.DefaultTimeout = "120s"
			}
			raw, err := config.MarshalYAML(cfg)
			if err != nil {
				return fmt.Errorf("marshal config: %w", err)
			}
			header := "# Generated by quench init — warm-sandbox, diff-aware verification\n" +
				"# Tip: read from another branch with --config origin/main:quench.yaml\n" +
				"# Tip: set per-check env vars via checks[].env (e.g. CGO_ENABLED: \"1\")\n"
			if err := os.WriteFile(outPath, append([]byte(header), raw...), 0o644); err != nil {
				return fmt.Errorf("write %s: %w", outPath, err)
			}
			fmt.Fprintf(cmd.OutOrStdout(), "Created %s (detected stack: %s, image: %s)\n", outPath, cfg.Stack, cfg.Sandbox.Image)
			return nil
		},
	}

	cmd.Flags().BoolVarP(&force, "force", "f", false, "Overwrite existing quench.yaml")
	return cmd
}
